#!/usr/bin/env node
// Copies herdr/{mods,layouts} into Herdr's home as real files: Herdr doesn't hot-reload through symlinks.
// Refuses to overwrite a file that changed in Herdr's home since the last sync (--force to override).
import { createHash } from 'node:crypto';
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  renameSync,
  watch,
  writeFileSync,
} from 'node:fs';
import { homedir } from 'node:os';
import { basename, dirname, join, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOTS = ['mods', 'layouts'];
const hash = (buf) => createHash('sha256').update(buf).digest('hex');

function files(src) {
  return ROOTS.flatMap((root) =>
    existsSync(join(src, root))
      ? readdirSync(join(src, root), { recursive: true, withFileTypes: true })
          .filter((e) => e.isFile() && e.name !== '.DS_Store')
          .map((e) => relative(src, join(e.parentPath, e.name)))
      : [],
  );
}

// Only .js: JSON has no comments.
function withHeader(rel, source, data) {
  if (!rel.endsWith('.js')) return data;
  const header = `// GENERATED by mdello/herdr/sync.mjs. Do not edit here: changes are not tracked.\n// Source: ${source} (edit there, then \`yarn herdr:sync\`).\n`;
  return Buffer.concat([Buffer.from(header), data]);
}

// shortcut: files deleted from the repo stay in Herdr's home; delete them there by hand.
export function sync({ src, home, statePath, force = false }) {
  const state = existsSync(statePath) ? JSON.parse(readFileSync(statePath, 'utf8')) : {};
  const written = [];
  const conflicts = [];
  for (const rel of files(src)) {
    const data = withHeader(rel, join(src, rel), readFileSync(join(src, rel)));
    const want = hash(data);
    const dest = join(home, rel);
    const have = existsSync(dest) ? hash(readFileSync(dest)) : undefined;
    if (have === want) {
      state[rel] = want;
      continue;
    }
    if (have !== undefined && have !== state[rel] && !force) {
      conflicts.push(rel);
      continue;
    }
    mkdirSync(dirname(dest), { recursive: true });
    // Hidden temp + rename: Herdr ignores hidden files and never sees a half-written one.
    const tmp = join(dirname(dest), `.${basename(dest)}.sync`);
    writeFileSync(tmp, data);
    renameSync(tmp, dest);
    state[rel] = want;
    written.push(rel);
  }
  writeFileSync(statePath, `${JSON.stringify(state, null, 2)}\n`);
  return { written, conflicts };
}

function run(opts) {
  const { written, conflicts } = sync(opts);
  for (const rel of written) console.log(`synced ${rel}`);
  for (const rel of conflicts)
    console.error(
      `CONFLICT ${rel}: changed in ${opts.home} since last sync. Copy it back into the repo, or rerun with --force to discard it.`,
    );
  return conflicts.length === 0;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const src = dirname(fileURLToPath(import.meta.url));
  const opts = {
    src,
    home: process.env.HERDR_APP_HOME ?? join(homedir(), '.config/herdr-app'),
    statePath: join(src, '.sync-state.json'),
    force: process.argv.includes('--force'),
  };
  const ok = run(opts);
  if (!process.argv.includes('--watch')) process.exit(ok ? 0 : 1);
  let timer;
  for (const root of ROOTS)
    watch(join(src, root), { recursive: true }, () => {
      clearTimeout(timer);
      timer = setTimeout(() => run(opts), 100);
    });
  console.log(`watching ${src} -> ${opts.home}`);
}
